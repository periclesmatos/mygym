-- Schema criado pelo Hibernate (ddl-auto: update) até o commit 647041f.
-- Bancos que já existiam são marcados nesta versão (baseline) e não rodam este arquivo.
-- Os nomes das constraints são os que o Hibernate gerou, para baterem com esses bancos.

CREATE TABLE app_user (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    CONSTRAINT uk1j9d9a06i600gd43uu3km82jw UNIQUE (email)
);

CREATE TABLE template (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    name       varchar(80)                 NOT NULL,
    notes      varchar(2000),
    "position" integer,
    updated_at timestamp(6) with time zone NOT NULL,
    user_id    bigint                      NOT NULL,
    CONSTRAINT fkr0dpc2e5ejsv0ufp198gnxi3v FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE template_exercise (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    load         numeric(6, 2),
    name         varchar(80) NOT NULL,
    planned_sets integer     NOT NULL,
    "position"   integer     NOT NULL,
    reps         varchar(20) NOT NULL,
    rest_seconds integer     NOT NULL,
    rir          integer,
    template_id  bigint      NOT NULL,
    CONSTRAINT fk3u3evxmibgsjrpsdp5fux9vrv FOREIGN KEY (template_id) REFERENCES template (id)
);

CREATE TABLE workout_session (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finished_at timestamp(6) with time zone,
    name        varchar(80)                 NOT NULL,
    started_at  timestamp(6) with time zone NOT NULL,
    template_id bigint,
    user_id     bigint                      NOT NULL,
    CONSTRAINT fk2c1bvqkv3bw7uypewu8mow8fw FOREIGN KEY (template_id) REFERENCES template (id),
    CONSTRAINT fkefwtlswnenflkgoou1kbvekn2 FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE session_exercise (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(80) NOT NULL,
    "position"   integer     NOT NULL,
    rest_seconds integer     NOT NULL,
    target_load  numeric(6, 2),
    target_reps  varchar(20) NOT NULL,
    target_rir   integer,
    session_id   bigint      NOT NULL,
    CONSTRAINT fkagddj0r3eiqg5c9abknwhijih FOREIGN KEY (session_id) REFERENCES workout_session (id)
);

CREATE TABLE workout_set (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completed_at timestamp(6) with time zone,
    carga        numeric(6, 2),
    "position"   integer NOT NULL,
    reps         integer,
    rir          integer,
    exercise_id  bigint  NOT NULL,
    CONSTRAINT fka01xnie65nrar2rlbgrfm5476 FOREIGN KEY (exercise_id) REFERENCES session_exercise (id)
);
