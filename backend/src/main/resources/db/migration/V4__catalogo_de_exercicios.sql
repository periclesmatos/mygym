-- 4. Preenche o grupo dos exercícios de rotina que batem com um nome ou apelido do catálogo.
UPDATE template_exercise te
SET muscle_group = c.muscle_group
FROM exercise_catalog c
WHERE c.user_id IS NULL
  AND te.muscle_group IS NULL
  AND (lower(trim(te.name)) = lower(c.name)
       OR lower(trim(te.name)) = ANY (string_to_array(lower(c.aliases), '|')));
