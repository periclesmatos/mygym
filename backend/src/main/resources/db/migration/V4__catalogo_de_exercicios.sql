-- Catálogo de exercícios e grupo muscular nos exercícios da rotina.

-- 1. Catálogo: exercícios do app (user_id nulo) e os criados por cada usuário.
--    aliases: outros nomes e grafias, separados por "|"; secondary_groups separados por ",".
CREATE TABLE exercise_catalog (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint REFERENCES app_user (id) ON DELETE CASCADE,
    name             varchar(80)  NOT NULL,
    aliases          varchar(300),
    muscle_group     varchar(20)  NOT NULL,
    secondary_groups varchar(120),
    equipment        varchar(20),
    kind             varchar(10)  NOT NULL DEFAULT 'isolado',
    planned_sets     integer      NOT NULL DEFAULT 3,
    reps             varchar(20)  NOT NULL DEFAULT '10-12',
    rest_seconds     integer      NOT NULL DEFAULT 90
);
-- Um nome por dono; os do app contam como dono 0.
CREATE UNIQUE INDEX uk_exercise_catalog_owner_name ON exercise_catalog (coalesce(user_id, 0), lower(name));
CREATE INDEX idx_exercise_catalog_user ON exercise_catalog (user_id);

-- 2. Grupo muscular escolhido no exercício da rotina (nulo nos antigos: o app deduz pelo nome).
ALTER TABLE template_exercise ADD COLUMN muscle_group varchar(20);

