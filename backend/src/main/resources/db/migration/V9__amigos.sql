-- Amigos: como cada pessoa é achada e quem é amigo de quem.

-- 1. public_id é o que sai para outras pessoas: o id sequencial deixaria listar todas as contas.
--    Telefone não é único, para ninguém travar o número de outra pessoa.
ALTER TABLE app_user
    ADD COLUMN public_id        uuid        NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    ADD COLUMN username         varchar(20) UNIQUE CHECK (username ~ '^[a-z][a-z0-9_]{2,19}$'),
    ADD COLUMN phone            varchar(16),
    ADD COLUMN phone_searchable boolean     NOT NULL DEFAULT false,
    ADD COLUMN email_searchable boolean     NOT NULL DEFAULT true;
CREATE INDEX idx_app_user_phone ON app_user (phone);

-- 2. Um par, uma linha: o menor id sempre em user_low. accepted_at nulo é pedido pendente.
CREATE TABLE friendship (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low     bigint                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    user_high    bigint                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    requested_by bigint                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at   timestamp(6) with time zone NOT NULL,
    accepted_at  timestamp(6) with time zone,
    UNIQUE (user_low, user_high),
    CHECK (user_low < user_high),
    CHECK (requested_by IN (user_low, user_high))
);
CREATE INDEX idx_friendship_high ON friendship (user_high);

CREATE TABLE user_block (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id bigint                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    blocked_id bigint                      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at timestamp(6) with time zone NOT NULL,
    UNIQUE (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);
CREATE INDEX idx_user_block_blocked ON user_block (blocked_id);
